// (x, y) のピクセルを color にする。画面の外は何もしない
// main.cpp の set_pixel と同じ働き。static を付けると、この関数はこのファイルの中だけで使える
// （付けないと、ほかのファイルに同じ名前の関数があるとき、リンクできなくなる）
// Set the pixel at (x, y) to color. Do nothing outside the screen.
// Works like set_pixel in main.cpp. static keeps this function local to this file.
// (Without it, linking can fail if another file has a function with the same name.)
static void put_pixel(Canvas& canvas, int x, int y, Color color) {
    // はみ出して pixels の外を書くと、プログラムが壊れるため
    // Writing past the end of pixels would break the program.
    if (x < 0 || x >= canvas.width || y < 0 || y >= canvas.height) {
        return;
    }
    canvas.pixels[y * canvas.width + x] = color;
}

// 文字を1つ描く。(x, y) は文字の左上、scale は拡大の倍率
// Draw one character. (x, y) is its top-left corner, and scale is the enlargement factor.
void draw_char(Canvas& canvas, int x, int y, char c, Color color, int scale) {
    // char は、環境によって負の数にもなる。0〜255 として扱うために、unsigned char に直してから番号を求める
    // 表の外を読むとプログラムが壊れるので、表にない文字は '?' で代わりにする
    // char can be negative on some systems. Convert it to unsigned char before getting its index so it is treated as a value from 0 to 255.
    // Reading past the table would break the program, so use '?' for characters not in the table.
    int index = static_cast<unsigned char>(c) - first_char;
    if (index < 0 || index >= char_count) {
        index = '?' - first_char;
    }

    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            // 行の左端（col = 0）が一番上のビット 0x80。col が増えるたびに、見るビットを1つ下へずらす
            // The leftmost column (col = 0) uses the highest bit, 0x80. Move down one bit each time col increases.
            const int mask = 0x80 >> col;
            if ((font[index][row] & mask) == 0) {
                continue;
            }

            // 1つの点を、scale × scale ピクセルの四角にして打つ
            // Draw one dot as a scale × scale pixel square.
            for (int dy = 0; dy < scale; dy++) {
                for (int dx = 0; dx < scale; dx++) {
                    put_pixel(canvas, x + col * scale + dx, y + row * scale + dy, color);
                }
            }
        }
    }
}

// 文字列を (x, y) から右へ並べて描く
// Draw a string from (x, y), moving to the right.
void draw_text(Canvas& canvas, int x, int y, const char* text, Color color, int scale) {
    int cursor_x = x;
    int cursor_y = y;

    // 文字列の終わりには '\0' が入っている。そこまで1文字ずつ進む
    // A string ends with '\0'. Move forward one character at a time until it is reached.
    for (int i = 0; text[i] != '\0'; i++) {
        // 改行は、文字としては描かず、左端に戻って1行下へ進む
        // Do not draw a newline as a character. Return to the left edge and move down one line.
        if (text[i] == '\n') {
            cursor_x = x;
            cursor_y += text_line_height * scale;
            continue;
        }

        draw_char(canvas, cursor_x, cursor_y, text[i], color, scale);
        cursor_x += text_char_width * scale;
    }
}
